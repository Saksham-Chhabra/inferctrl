"""Schemas for serving configurations and knobs."""

from typing import Dict, Optional
from pydantic import BaseModel, Field, field_validator


class ServingConfig(BaseModel):
    """Serving configuration parameters and knobs."""
    config_id: str
    version: int = 1
    max_concurrency: int = Field(default=8, ge=1, le=64, description="Concurrent requests per worker/GPU")
    max_batch_size: int = Field(default=16, ge=1, le=128, description="Max batch size for prefill/decode")
    batch_wait_ms: float = Field(default=20.0, ge=0.0, le=100.0, description="Max wait time for batch formation")
    routing_mix: Dict[str, float] = Field(
        default_factory=lambda: {"llama-3-8b": 0.70, "llama-3-70b": 0.30},
        description="Traffic fraction routed to each model ID"
    )
    speculative_decoding: bool = Field(default=False)
    draft_length: int = Field(default=0, ge=0, le=8)
    replica_count: int = Field(default=4, ge=1, le=16)

    @field_validator("routing_mix")
    @classmethod
    def validate_routing_sum(cls, v: Dict[str, float]) -> Dict[str, float]:
        if not v:
            raise ValueError("routing_mix cannot be empty")
        total = sum(v.values())
        if abs(total - 1.0) > 1e-4:
            raise ValueError(f"routing_mix weights must sum to 1.0, got {total}")
        return v


class CandidateProposal(BaseModel):
    """Proposal generated by Scheduler Agent."""
    candidate_id: str
    run_id: str
    parent_config_id: str
    config: ServingConfig
    hypothesis: str
    targeted_knob: str  # e.g., "batch_wait_ms", "routing_mix"
    expected_tradeoff: str
    validation_passed: bool = False
    rejection_reasons: list[str] = Field(default_factory=list)

